class Solution {
    public long countCommas(long n) {
        //int totalCommas=0;
        if(n<1000)return 0;
        if(n<1_000_000){
           return n-999; 
        }
        if(n<1_000_000_000){
            return 999_000+(n-999_999)*2;
        }
        if(n<1_000_000_000_000L){
            return (long)(999_000+(999_000_000L*2)+(n-999_999_999L)*3);
        }
        if(n<1_000_000_000_000_000L){
            return (long)(999_000+(999_000_000L*2)+(999_000_000_000L*3)+(n-999_999_999_999L)*4);
        }
        if(n<1_000_000_000_000_000_000L){
            return (long)(999_000+(999_000_000L*2)+(999_000_000_000L*3)+(999_000_000_000_000L*4)+(n-999_999_999_999_999L)*5);
        }
        return 0;
    }
}